# ===========================================================
# Emitter: handles indentation and lines
# ===========================================================


class Emitter:
    """Accumulator of output lines with automatic indentation."""

    def __init__(self, indent_unit: str = "    "):
        self.lines: list[str] = []
        self._indent = 0
        self._unit = indent_unit

    def write(self, line: str) -> None:
        if line == "":
            self.lines.append("")
        else:
            self.lines.append(self._unit * self._indent + line)

    def blank(self) -> None:
        # Only add a blank line if the last one is not already blank.
        if self.lines and self.lines[-1] != "":
            self.lines.append("")

    def indent(self) -> None:
        self._indent += 1

    def dedent(self) -> None:
        self._indent -= 1
        assert self._indent >= 0

    def current_line(self) -> int:
        # 1-based number of the most recently emitted physical line.
        # The next ``write`` lands on ``current_line() + 1``. Counts
        # embedded newlines because some entries (notably the prelude)
        # are appended as a single multi-line string rather than one
        # call to ``write`` per line.
        return sum(entry.count("\n") + 1 for entry in self.lines)

    def get(self) -> str:
        # Ensures the file ends with a newline and has no trailing
        # blank lines.
        text = "\n".join(self.lines).rstrip() + "\n"
        return text


