"""Aggregate decisions.csv into the headline tables + figure that
feed paper §5.1.

Reads ``decisions.csv`` (output of ``classify.py``, optionally
refined by a manual review pass that fills the ``reviewer_note``
column and adjusts ``bucket``), then emits:

- ``summary.csv``: one row per (year, bucket) with a count column.
  Convenient for the LaTeX table generator.
- ``summary.png``: stacked-bar chart of bucket counts per year.
  Only written if matplotlib is importable; otherwise the script
  prints a notice and the CSV is still produced.
- ``summary.md``: a Markdown table mirroring summary.csv +
  overall totals + bucket descriptions. The paper draft can
  ``include`` this fragment, or copy-paste the numbers.

Usage:
    python -m evaluation.cve.summary
"""

from __future__ import annotations

import argparse
import csv
import sys
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

DECISIONS_PATH = Path(__file__).parent / "decisions.csv"
SUMMARY_CSV = Path(__file__).parent / "summary.csv"
SUMMARY_PNG = Path(__file__).parent / "summary.png"
SUMMARY_MD = Path(__file__).parent / "summary.md"

BUCKET_ORDER = [
    "STRUCTURAL_REJECT",
    "ATTENUATION_MITIGATED",
    "OUT_OF_SCOPE_MEMORY",
    "OUT_OF_SCOPE_LOGIC",
    "OUT_OF_SCOPE_BELOW_LANG",
    "UNCLEAR",
]

BUCKET_DESCRIPTION = {
    "STRUCTURAL_REJECT": (
        "Exploit requires a capability the legitimate function "
        "would not have declared; Capa rejects the call shape "
        "before the exploit runs."
    ),
    "ATTENUATION_MITIGATED": (
        "Capability is legitimately needed; attenuation "
        "(Fs.restrict_to / Net.restrict_to) reduces blast radius."
    ),
    "OUT_OF_SCOPE_MEMORY": (
        "Memory-safety / UB bug in unsafe code or C dependency; "
        "Capa's capability layer has no opinion."
    ),
    "OUT_OF_SCOPE_LOGIC": (
        "Application-layer logic / auth flaw; capabilities do "
        "not help."
    ),
    "OUT_OF_SCOPE_BELOW_LANG": (
        "Bug below the language layer (kernel, linker, firmware, "
        "build tooling)."
    ),
    "UNCLEAR": (
        "Not enough signal in the NVD entry alone; reviewer "
        "could not decide."
    ),
}


@dataclass
class Aggregate:
    """One row of summary.csv."""

    year: int
    bucket: str
    count: int


def _load_decisions() -> list[dict]:
    if not DECISIONS_PATH.exists():
        print(
            f"[summary] {DECISIONS_PATH} not found; run "
            f"`python -m evaluation.cve.classify` first.",
            file=sys.stderr,
        )
        sys.exit(2)
    with DECISIONS_PATH.open(encoding="utf-8") as f:
        return list(csv.DictReader(f))


def _aggregate(rows: list[dict]) -> tuple[list[Aggregate], dict[str, int]]:
    """Aggregate per (year, bucket); also return overall totals
    by bucket for the headline %s."""
    per_yb: dict[tuple[int, str], int] = defaultdict(int)
    per_b: dict[str, int] = defaultdict(int)
    for r in rows:
        year = int(r["year"])
        bucket = r["bucket"]
        per_yb[(year, bucket)] += 1
        per_b[bucket] += 1
    aggs = [
        Aggregate(year=year, bucket=bucket, count=count)
        for (year, bucket), count in sorted(per_yb.items())
    ]
    return aggs, dict(per_b)


def _write_csv(aggs: list[Aggregate]) -> None:
    with SUMMARY_CSV.open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(["year", "bucket", "count"])
        for a in aggs:
            w.writerow([a.year, a.bucket, a.count])


def _write_md(aggs: list[Aggregate], totals: dict[str, int], n: int) -> None:
    lines: list[str] = []
    lines.append(
        "# CVE classification summary "
        f"(N={n}, NVD 2018-2024 HIGH/CRIT slice)"
    )
    lines.append("")
    lines.append(
        "Generated by `python -m evaluation.cve.summary` from "
        "`decisions.csv`. Re-run after any manual reviewer edits."
    )
    lines.append("")
    lines.append("## Bucket totals")
    lines.append("")
    lines.append("| Bucket | Count | % of N | Description |")
    lines.append("|---|---:|---:|---|")
    for bucket in BUCKET_ORDER:
        count = totals.get(bucket, 0)
        pct = (count / n * 100.0) if n else 0.0
        desc = BUCKET_DESCRIPTION[bucket]
        lines.append(f"| {bucket} | {count} | {pct:.1f}% | {desc} |")
    lines.append("")
    cap_helped = (
        totals.get("STRUCTURAL_REJECT", 0)
        + totals.get("ATTENUATION_MITIGATED", 0)
    )
    cap_pct = (cap_helped / n * 100.0) if n else 0.0
    lines.append(
        f"**Headline: {cap_helped}/{n} ({cap_pct:.1f}%) of capability-"
        f"relevant CVEs in the slice fall in buckets Capa's discipline "
        f"would meaningfully address (STRUCTURAL_REJECT + "
        f"ATTENUATION_MITIGATED).**"
    )
    lines.append("")
    lines.append("## Per-year breakdown")
    lines.append("")
    lines.append(
        "| Year | "
        + " | ".join(BUCKET_ORDER)
        + " | Total |"
    )
    lines.append(
        "|---|"
        + "|".join("---:" for _ in BUCKET_ORDER)
        + "|---:|"
    )
    years = sorted({a.year for a in aggs})
    for year in years:
        row = [str(year)]
        total = 0
        for bucket in BUCKET_ORDER:
            count = sum(
                a.count for a in aggs
                if a.year == year and a.bucket == bucket
            )
            row.append(str(count))
            total += count
        row.append(str(total))
        lines.append("| " + " | ".join(row) + " |")
    SUMMARY_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _write_png(aggs: list[Aggregate]) -> bool:
    try:
        import matplotlib
        matplotlib.use("Agg")  # headless rendering, no display required
        import matplotlib.pyplot as plt
    except ImportError:
        print(
            "[summary] matplotlib unavailable; skipping PNG. Install "
            "with `pip install -e .[eval]` to enable.",
            file=sys.stderr,
        )
        return False

    years = sorted({a.year for a in aggs})
    bottom = [0] * len(years)
    colors = {
        "STRUCTURAL_REJECT": "#2c7fb8",
        "ATTENUATION_MITIGATED": "#7fcdbb",
        "OUT_OF_SCOPE_MEMORY": "#d9d9d9",
        "OUT_OF_SCOPE_LOGIC": "#bdbdbd",
        "OUT_OF_SCOPE_BELOW_LANG": "#969696",
        "UNCLEAR": "#737373",
    }
    fig, ax = plt.subplots(figsize=(8.5, 4.5))
    for bucket in BUCKET_ORDER:
        counts = [
            sum(a.count for a in aggs if a.year == y and a.bucket == bucket)
            for y in years
        ]
        ax.bar(
            years, counts,
            label=bucket, bottom=bottom, color=colors[bucket],
            edgecolor="white", linewidth=0.6,
        )
        bottom = [b + c for b, c in zip(bottom, counts)]

    ax.set_xlabel("Year")
    ax.set_ylabel("CVE count")
    ax.set_title(
        f"Capability-relevant CVE classification "
        f"(NVD 2018-2024 HIGH/CRIT, N={sum(a.count for a in aggs)})"
    )
    ax.legend(loc="upper left", fontsize=8, frameon=False)
    ax.set_xticks(years)
    fig.tight_layout()
    fig.savefig(SUMMARY_PNG, dpi=144)
    plt.close(fig)
    return True


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Summarise decisions.csv")
    p.parse_args(argv)

    rows = _load_decisions()
    aggs, totals = _aggregate(rows)
    n = sum(totals.values())

    _write_csv(aggs)
    _write_md(aggs, totals, n)
    png_written = _write_png(aggs)

    print(f"[summary] wrote {SUMMARY_CSV}")
    print(f"[summary] wrote {SUMMARY_MD}")
    if png_written:
        print(f"[summary] wrote {SUMMARY_PNG}")

    cap_helped = (
        totals.get("STRUCTURAL_REJECT", 0)
        + totals.get("ATTENUATION_MITIGATED", 0)
    )
    cap_pct = (cap_helped / n * 100.0) if n else 0.0
    print()
    print(f"[summary] headline: {cap_helped}/{n} ({cap_pct:.1f}%) Capa-relevant")
    for bucket in BUCKET_ORDER:
        count = totals.get(bucket, 0)
        pct = (count / n * 100.0) if n else 0.0
        print(f"  {bucket}: {count}  ({pct:.1f}%)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
