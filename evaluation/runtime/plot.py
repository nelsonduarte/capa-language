"""Plot runtime.results.csv into a grouped-bar figure +
companion markdown table for the paper.

Reads ``evaluation/runtime/results.csv`` (output of
``harness.py``) and emits:

- ``summary.md``: a Markdown table the paper draft can paste
  in directly. Includes the wall-clock ratio (wasm / python) per
  workload -- the headline figure.
- ``results.png``: grouped bar chart, one group per workload,
  two bars (capa_python, capa_wasm). Error bars from the
  per-trial min/max range.

Matplotlib is optional (install with ``pip install -e .[eval]``);
if absent the markdown is still produced.
"""

from __future__ import annotations

import argparse
import csv
import sys
from dataclasses import dataclass
from pathlib import Path

RESULTS_CSV = Path(__file__).parent / "results.csv"
SUMMARY_PNG = Path(__file__).parent / "results.png"
SUMMARY_MD = Path(__file__).parent / "summary.md"


@dataclass
class Row:
    workload: str
    backend: str
    n_ok: int
    n_trials: int
    seconds_mean: float
    seconds_min: float
    seconds_max: float
    seconds_stdev: float
    rss_mb_max: float


def _load() -> list[Row]:
    if not RESULTS_CSV.exists():
        print(
            f"[plot] {RESULTS_CSV} not found; run "
            f"`python -m evaluation.runtime.harness` first.",
            file=sys.stderr,
        )
        sys.exit(2)
    out: list[Row] = []
    with RESULTS_CSV.open(encoding="utf-8") as f:
        for r in csv.DictReader(f):
            out.append(Row(
                workload=r["workload"],
                backend=r["backend"],
                n_ok=int(r["n_ok"]),
                n_trials=int(r["n_trials"]),
                seconds_mean=float(r["seconds_mean"]),
                seconds_min=float(r["seconds_min"]),
                seconds_max=float(r["seconds_max"]),
                seconds_stdev=float(r["seconds_stdev"]),
                rss_mb_max=float(r["rss_mb_max"]),
            ))
    return out


def _write_md(rows: list[Row]) -> None:
    by_w: dict[str, dict[str, Row]] = {}
    for r in rows:
        by_w.setdefault(r.workload, {})[r.backend] = r

    lines: list[str] = []
    lines.append("# Runtime benchmark: capa_python vs capa_wasm at macro scale")
    lines.append("")
    lines.append(
        "Generated by `python -m evaluation.runtime.plot` from "
        "`results.csv`. Subprocess wall-clock of "
        "`python -m capa [--wasm] --run <demo>.capa <args>`. "
        "Each cell is the mean of N trials; the range column "
        "captures min-max."
    )
    lines.append("")
    lines.append(
        "| Workload | Trials | capa_python (s) | capa_wasm (s) | "
        "wasm/python | range (python) | range (wasm) |"
    )
    lines.append("|---|---:|---:|---:|---:|---|---|")
    for workload in sorted(by_w):
        pyrow = by_w[workload].get("capa_python")
        wsrow = by_w[workload].get("capa_wasm")
        if pyrow is None or wsrow is None:
            continue
        ratio = wsrow.seconds_mean / pyrow.seconds_mean if pyrow.seconds_mean else 0.0
        lines.append(
            f"| {workload} | {pyrow.n_trials} | "
            f"{pyrow.seconds_mean:.3f} | {wsrow.seconds_mean:.3f} | "
            f"{ratio:.2f}x | "
            f"[{pyrow.seconds_min:.3f}, {pyrow.seconds_max:.3f}] | "
            f"[{wsrow.seconds_min:.3f}, {wsrow.seconds_max:.3f}] |"
        )
    lines.append("")
    # Headline: aggregate ratio across all workloads.
    ratios = []
    for workload in by_w:
        py = by_w[workload].get("capa_python")
        ws = by_w[workload].get("capa_wasm")
        if py and ws and py.seconds_mean:
            ratios.append(ws.seconds_mean / py.seconds_mean)
    if ratios:
        mean_ratio = sum(ratios) / len(ratios)
        lines.append(
            f"**Headline: Capa --wasm pays {mean_ratio:.2f}x wall-clock "
            f"overhead vs Capa --python at the macro scale, averaged "
            f"across {len(ratios)} downstream demos.** The constant-cost "
            f"part of the Wasm path (wasmtime spin-up, JsonValue host "
            f"bridge initialisation, lazy host-import resolution) "
            f"dominates for sub-second workloads. Steady-state numbers "
            f"on longer-running workloads are expected to narrow this "
            f"gap; that measurement is future work."
        )
    lines.append("")
    lines.append("## Caveats")
    lines.append("")
    lines.append(
        "- **RSS column** in `results.csv` is unreliable on Windows "
        "for short-lived processes (psutil samples at 10ms; the "
        "Capa subprocesses exit in 250-500ms and the sampler "
        "often catches only the initial allocation state). The "
        "wall-clock numbers are the load-bearing metric for this "
        "slice."
    )
    lines.append(
        "- **Hand-Python and Node baselines** are not in this "
        "slice; the headline is strictly an apples-to-apples "
        "Capa-backend comparison. Adding those columns is "
        "follow-up work."
    )
    lines.append(
        "- **Cold-start dominated**: each trial is a fresh "
        "subprocess. Interpreter and wasmtime spin-up cost are "
        "counted; this is what a CLI user experiences. A "
        "long-running server would see the ratio collapse."
    )
    SUMMARY_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _write_png(rows: list[Row]) -> bool:
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        print(
            "[plot] matplotlib unavailable; skipping PNG. Install "
            "with `pip install -e .[eval]` to enable.",
            file=sys.stderr,
        )
        return False

    by_w: dict[str, dict[str, Row]] = {}
    for r in rows:
        by_w.setdefault(r.workload, {})[r.backend] = r
    workloads = sorted(by_w)

    py_means = [by_w[w]["capa_python"].seconds_mean for w in workloads]
    py_err_lo = [
        by_w[w]["capa_python"].seconds_mean - by_w[w]["capa_python"].seconds_min
        for w in workloads
    ]
    py_err_hi = [
        by_w[w]["capa_python"].seconds_max - by_w[w]["capa_python"].seconds_mean
        for w in workloads
    ]
    ws_means = [by_w[w]["capa_wasm"].seconds_mean for w in workloads]
    ws_err_lo = [
        by_w[w]["capa_wasm"].seconds_mean - by_w[w]["capa_wasm"].seconds_min
        for w in workloads
    ]
    ws_err_hi = [
        by_w[w]["capa_wasm"].seconds_max - by_w[w]["capa_wasm"].seconds_mean
        for w in workloads
    ]

    fig, ax = plt.subplots(figsize=(7.5, 4.0))
    x = list(range(len(workloads)))
    width = 0.36
    ax.bar(
        [xi - width / 2 for xi in x],
        py_means, width=width, label="capa --python",
        color="#2c7fb8", yerr=[py_err_lo, py_err_hi], capsize=4,
    )
    ax.bar(
        [xi + width / 2 for xi in x],
        ws_means, width=width, label="capa --wasm",
        color="#fdae6b", yerr=[ws_err_lo, ws_err_hi], capsize=4,
    )
    for xi, w in zip(x, workloads):
        py = by_w[w]["capa_python"].seconds_mean
        ws = by_w[w]["capa_wasm"].seconds_mean
        ax.text(
            xi + width / 2, ws + 0.015,
            f"{ws / py:.2f}x" if py else "n/a",
            ha="center", fontsize=9, color="#444",
        )

    ax.set_xticks(x)
    ax.set_xticklabels(workloads)
    ax.set_ylabel("wall-clock (s, lower is better)")
    ax.set_title(
        "Runtime: Capa --python vs --wasm at macro scale "
        f"(N={rows[0].n_trials} trials, cold start)"
    )
    ax.legend(loc="upper left", frameon=False)
    ax.grid(axis="y", linestyle=":", alpha=0.5)
    fig.tight_layout()
    fig.savefig(SUMMARY_PNG, dpi=144)
    plt.close(fig)
    return True


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Plot runtime results")
    p.parse_args(argv)

    rows = _load()
    _write_md(rows)
    png_written = _write_png(rows)
    print(f"[plot] wrote {SUMMARY_MD}")
    if png_written:
        print(f"[plot] wrote {SUMMARY_PNG}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
