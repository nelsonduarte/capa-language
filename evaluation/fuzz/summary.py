"""Aggregate fuzz/results.csv into a paper-ready markdown
summary.

Reads ``evaluation/fuzz/results.csv`` (output of ``harness.py
--all``), groups attempts by category, and emits ``summary.md``
with per-category counts + a headline pass/fail line.

The paper §5.5 ("Soundness empirics") table comes directly from
this file. Re-run after any panel expansion or analyzer change.
"""

from __future__ import annotations

import argparse
import csv
import sys
from collections import defaultdict
from pathlib import Path

RESULTS_CSV = Path(__file__).parent / "results.csv"
SUMMARY_MD = Path(__file__).parent / "summary.md"


def _load() -> list[dict]:
    if not RESULTS_CSV.exists():
        print(
            f"[fuzz-summary] {RESULTS_CSV} not found; run "
            f"`python -m evaluation.fuzz.harness --all` first.",
            file=sys.stderr,
        )
        sys.exit(2)
    with RESULTS_CSV.open(encoding="utf-8") as f:
        return list(csv.DictReader(f))


def _write_md(rows: list[dict]) -> None:
    per_cat: dict[str, list[dict]] = defaultdict(list)
    for r in rows:
        per_cat[r["category"]].append(r)

    total = len(rows)
    n_rejected = sum(1 for r in rows if r["rejected"].lower() == "true")
    n_escaped = total - n_rejected

    lines: list[str] = []
    lines.append(
        "# Soundness fuzz panel: capability-bypass attempts vs `capa --check`"
    )
    lines.append("")
    lines.append(
        "Generated by `python -m evaluation.fuzz.summary` from "
        "`results.csv`. Each row is one attack program written to "
        "exercise a specific capability-bypass shape; the analyzer "
        "either rejects it at `--check` time (the discipline holds) "
        "or accepts it (an escape, paper-critical to investigate)."
    )
    lines.append("")
    lines.append(
        f"## Headline: {n_rejected}/{total} rejected, "
        f"{n_escaped} escaped"
    )
    lines.append("")
    if n_escaped == 0:
        lines.append(
            f"**The capability discipline holds across all "
            f"{total} negative tests in the panel.** No attack "
            f"shape currently in scope produced an accepted program."
        )
    else:
        lines.append(
            f"**{n_escaped} escape(s) detected.** Each is a "
            f"paper-critical finding -- see the per-category table "
            f"below and the `description` column of `results.csv`."
        )
    lines.append("")
    lines.append("## Per-category breakdown")
    lines.append("")
    lines.append("| Category | Attempts | Rejected | Escaped |")
    lines.append("|---|---:|---:|---:|")
    for cat in sorted(per_cat):
        attempts = len(per_cat[cat])
        rejected = sum(
            1 for r in per_cat[cat] if r["rejected"].lower() == "true"
        )
        escaped = attempts - rejected
        marker = "" if escaped == 0 else " **ESCAPE**"
        lines.append(
            f"| `{cat}` | {attempts} | {rejected} | {escaped}{marker} |"
        )
    lines.append("")
    lines.append("## Coverage")
    lines.append("")
    lines.append(
        "The panel covers the eight attack categories called out "
        "in the empirical-study plan:"
    )
    lines.append("")
    descriptions = {
        "cat_fs_traversal": "Filesystem read of sensitive paths from no-Fs functions.",
        "cat_env_leak": "Environment-variable exfiltration without Env.",
        "cat_net_punch": "Outbound network connection without Net.",
        "cat_time_channel": "Wall-clock reads (for side-channel exploitation) without Clock.",
        "cat_subprocess": "Subprocess spawn (sh, curl, powershell, ...) without Proc.",
        "cat_unsafe_smuggle": "Calls to `py_import` / `py_invoke` (the Unsafe-gated escape hatches) without Unsafe.",
        "cat_capability_in_data": "Hiding a built-in capability inside a struct field / variant payload / tuple / generic / let / const.",
        "cat_capability_aliasing": "Passing the same capability twice in a single call (aliasing).",
        "cat_llm_dispatch_escape": "LLM-agent-shaped programs trying to escape the §5.4 sandbox by forging or aliasing caps.",
    }
    for cat in sorted(per_cat):
        if cat in descriptions:
            lines.append(f"- `{cat}`: {descriptions[cat]}")
    lines.append("")
    lines.append("## Methodology")
    lines.append("")
    lines.append(
        "Each attack program is hand-written to target a "
        "specific bypass shape, written to a temp `.capa` file, "
        "and passed to `python -m capa --check` as a subprocess. "
        "Rejection iff exit code != 0. No probabilistic fuzzing "
        "of input mutations; the panel is exhaustive of the "
        "categories rather than randomised within them."
    )
    lines.append("")
    lines.append(
        "**An escape detected here is a paper-relevant finding.** "
        "Two such findings were surfaced and fixed during the "
        "build-out of this slice: the capability-forge bypass "
        "(commit 67d9878) and the user-defined-cap aliasing "
        "bypass (commit on the same day). Both were silent "
        "soundness regressions in the legacy --python backend "
        "that --wasm was incidentally protected against."
    )
    SUMMARY_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Summarise fuzz results")
    p.parse_args(argv)
    rows = _load()
    _write_md(rows)
    print(f"[fuzz-summary] wrote {SUMMARY_MD}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
